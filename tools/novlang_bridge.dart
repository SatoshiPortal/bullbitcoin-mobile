// ignore_for_file: avoid_print
//
// novlang_bridge.dart — dev-only generator for the novlang overrides.
//
// Run by `make translations` after every `gen-l10n`. It reads
// `packages/novlang/manifest.yaml` and the code gen-l10n already generated for
// the root catalogue, and writes (git-ignored)
// `lib/generated/novlang/novlang_app_localizations.dart`:
//
//   * one `NovlangAppLocalizations<Lang>` class per generated
//     `AppLocalizations<Lang>` class, extending it, so locale/script/region
//     resolution stays entirely gen-l10n's;
//   * a mixin that overrides ONLY the manifest keys (getters and methods, with
//     the signatures gen-l10n generated, so ICU stays gen-l10n's job) and reads
//     the `NovlangLocalizations` override when the policy of the entry's store
//     applies, otherwise `super` (the real word);
//   * `NovlangAppLocalizationsDelegate`, the delegate the shell composes ahead
//     of `AppLocalizations.delegate`.
//
// A manifest key that no longer exists in the catalogue fails this tool; an
// override key missing from the novlang catalogue fails compilation. Nothing
// here patches generated code or parses ICU.
//
// Usage (from the repository root): dart tools/novlang_bridge.dart
// (`dart run` would trigger the native build hooks of the app for nothing.)

import 'dart:io';

import 'package:yaml/yaml.dart';

const _manifestPath = 'packages/novlang/manifest.yaml';
const _l10nDir = 'lib/generated/l10n';
const _arbDir = 'localization';
const _outputPath = 'lib/generated/novlang/novlang_app_localizations.dart';

void main(List<String> args) {
  final entries = _readManifest();
  final signatures = _readSignatures();
  final locales = _readLocaleClasses();

  final arbCount = Directory(_arbDir)
      .listSync()
      .whereType<File>()
      .where((f) => RegExp(r'app_[\w]+\.arb$').hasMatch(f.path))
      .length;
  if (locales.length != arbCount) {
    stderr.writeln(
      'Found ${locales.length} generated locale classes for $arbCount '
      'catalogues in $_arbDir: a language would silently keep the real words. '
      'Run gen-l10n first, or extend this tool if gen-l10n changed its output.',
    );
    exit(1);
  }

  final missing = [
    for (final e in entries)
      if (!signatures.containsKey(e.key)) e.key,
  ];
  if (missing.isNotEmpty) {
    stderr.writeln(
      'novlang manifest keys missing from the root catalogue: '
      '${missing.join(', ')}',
    );
    exit(1);
  }

  final stores = {for (final e in entries) e.store}.toList()..sort();
  final out = StringBuffer()
    ..writeln('// GENERATED by tools/novlang_bridge.dart. Do not edit.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln("import 'package:bb_mobile/generated/l10n/localization.dart';");
  for (final file in locales.map((c) => c.file).toSet().toList()..sort()) {
    out.writeln("import 'package:bb_mobile/generated/l10n/$file';");
  }
  out
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln("import 'package:novlang/novlang.dart';")
    ..writeln()
    ..writeln(
      '/// Overrides only the keys of the novlang manifest; every other\n'
      '/// message comes from the catalogue untouched.',
    )
    ..writeln('mixin NovlangAppOverrides on AppLocalizations {')
    ..writeln('  NovlangPolicy get novlangPolicy;')
    ..writeln('  NovlangLocalizations get novlang;');
  for (final e in entries) {
    final s = signatures[e.key]!;
    final value = 'novlang.app__${e.key}_${e.store}';
    final applies = 'novlangPolicy == NovlangPolicy.${e.store}';
    out.writeln();
    out.writeln('  @override');
    if (s.params == null) {
      out
        ..writeln('  String get ${e.key} =>')
        ..writeln('      $applies ? $value : super.${e.key};');
    } else {
      final names = _paramNames(s.params!);
      final call = names.isEmpty ? '' : names.join(', ');
      out
        ..writeln('  String ${e.key}(${s.params}) =>')
        ..writeln('      $applies ? $value($call) : super.${e.key}($call);');
    }
  }
  out.writeln('}');

  for (final c in locales) {
    out
      ..writeln()
      ..writeln(
        'class ${c.novlangName} extends ${c.name} with NovlangAppOverrides {',
      )
      ..writeln('  ${c.novlangName}(this.novlangPolicy, this.novlang);')
      ..writeln()
      ..writeln('  @override')
      ..writeln('  final NovlangPolicy novlangPolicy;')
      ..writeln()
      ..writeln('  @override')
      ..writeln('  final NovlangLocalizations novlang;')
      ..writeln('}');
  }

  out
    ..writeln()
    ..writeln('/// Policies with at least one override in the manifest.')
    ..writeln('const _constrainedPolicies = <NovlangPolicy>{')
    ..writeln([for (final s in stores) '  NovlangPolicy.$s,'].join('\n'))
    ..writeln('};')
    ..writeln()
    ..writeln(
      '/// Serves [AppLocalizations] with the store vocabulary of [policy].\n'
      '///\n'
      '/// Place it BEFORE `AppLocalizations.delegate`: Flutter uses the first\n'
      '/// delegate of a type. The locale is resolved by gen-l10n; this only\n'
      '/// wraps the result.',
    )
    ..writeln(
      'class NovlangAppLocalizationsDelegate\n'
      '    extends LocalizationsDelegate<AppLocalizations> {',
    )
    ..writeln('  const NovlangAppLocalizationsDelegate(this.policy);')
    ..writeln()
    ..writeln('  final NovlangPolicy policy;')
    ..writeln()
    ..writeln('  @override')
    ..writeln(
      '  bool isSupported(Locale locale) =>\n'
      '      AppLocalizations.delegate.isSupported(locale);',
    )
    ..writeln()
    ..writeln('  @override')
    ..writeln('  Future<AppLocalizations> load(Locale locale) async {')
    ..writeln('    final base = await AppLocalizations.delegate.load(locale);')
    ..writeln('    if (!_constrainedPolicies.contains(policy)) return base;')
    ..writeln('    final novlang = lookupNovlangLocalizations(locale);')
    ..writeln('    return switch (base.localeName) {');
  for (final c in locales) {
    out.writeln(
      "      '${c.localeName}' => ${c.novlangName}(policy, novlang),",
    );
  }
  out
    ..writeln(
      "      _ => throw StateError('No novlang class for \${base.localeName}'),",
    )
    ..writeln('    };')
    ..writeln('  }')
    ..writeln()
    ..writeln('  @override')
    ..writeln(
      '  bool shouldReload(NovlangAppLocalizationsDelegate old) =>\n'
      '      old.policy != policy;',
    )
    ..writeln('}');

  out
    ..writeln()
    ..writeln(
      '/// The delegates of every MaterialApp showing catalogue text: the\n'
      '/// novlang delegate FIRST, then the stock ones. A MaterialApp that lists\n'
      '/// only `AppLocalizations.localizationsDelegates` would bypass novlang.',
    )
    ..writeln(
      'List<LocalizationsDelegate<dynamic>> novlangLocalizationsDelegates(\n'
      '  NovlangPolicy policy,\n'
      ') => [\n'
      '  NovlangAppLocalizationsDelegate(policy),\n'
      '  ...AppLocalizations.localizationsDelegates,\n'
      '];',
    );

  File(_outputPath)
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  print(
    'novlang: ${entries.length} overrides, ${locales.length} locale classes '
    '-> $_outputPath',
  );
}

class _Entry {
  const _Entry(this.key, this.store);
  final String key;
  final String store;
}

class _Signature {
  const _Signature(this.params);

  /// `null` for a getter, the raw parameter list for a method.
  final String? params;
}

class _LocaleClass {
  const _LocaleClass(this.name, this.file, this.localeName);
  final String name;
  final String file;
  final String localeName;
  String get novlangName => 'Novlang$name';
}

List<_Entry> _readManifest() {
  final yaml = loadYaml(File(_manifestPath).readAsStringSync()) as YamlMap;
  final stores = (yaml['stores'] as YamlMap).keys.cast<String>().toSet();
  final entries = <_Entry>[];
  final seen = <String>{};
  for (final raw in yaml['entries'] as YamlList) {
    final e = raw as YamlMap;
    final catalogue = e['catalogue'] as String;
    final key = e['key'] as String;
    final store = e['store'] as String;
    if (catalogue != 'app') {
      stderr.writeln('Unsupported novlang catalogue "$catalogue" for $key.');
      exit(1);
    }
    if (!stores.contains(store)) {
      stderr.writeln('Unknown store "$store" for $key.');
      exit(1);
    }
    if (!seen.add('$store/$key')) {
      stderr.writeln('Duplicate manifest entry $store/$key.');
      exit(1);
    }
    entries.add(_Entry(key, store));
  }
  return entries;
}

/// Getter and method signatures of the abstract [AppLocalizations].
Map<String, _Signature> _readSignatures() {
  final source = File('$_l10nDir/localization.dart').readAsStringSync();
  final re = RegExp(
    r'^  String (?:get (\w+)|(\w+)\(([^)]*)\));',
    multiLine: true,
  );
  final result = <String, _Signature>{};
  for (final m in re.allMatches(source)) {
    final getter = m.group(1);
    if (getter != null) {
      result[getter] = const _Signature(null);
    } else {
      result[m.group(2)!] = _Signature(_normalizeParams(m.group(3)!));
    }
  }
  return result;
}

String _normalizeParams(String raw) =>
    raw.replaceAll(RegExp(r'\s+'), ' ').trim().replaceAll(RegExp(r',$'), '');

List<String> _paramNames(String params) => [
  for (final p in params.split(','))
    if (p.trim().isNotEmpty) p.trim().split(' ').last,
];

/// Every generated `AppLocalizations<Lang>` class with its locale name.
List<_LocaleClass> _readLocaleClasses() {
  final classes = <_LocaleClass>[];
  final files =
      Directory(_l10nDir)
          .listSync()
          .whereType<File>()
          .where((f) => RegExp(r'localization_\w+\.dart$').hasMatch(f.path))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final langRe = RegExp(
    r"class (AppLocalizations\w+) extends AppLocalizations \{\s+"
    r"\1\(\[String locale = '(\w+)'\]\)",
  );
  final regionRe = RegExp(
    r"class (AppLocalizations\w+) extends AppLocalizations\w+ \{\s+"
    r"\1\(\) : super\('(\w+)'\);",
  );
  for (final f in files) {
    final source = f.readAsStringSync();
    final file = f.uri.pathSegments.last;
    for (final m in [
      ...langRe.allMatches(source),
      ...regionRe.allMatches(source),
    ]) {
      classes.add(_LocaleClass(m.group(1)!, file, m.group(2)!));
    }
  }
  if (classes.isEmpty) {
    stderr.writeln('No generated locale class found in $_l10nDir.');
    exit(1);
  }
  return classes;
}
