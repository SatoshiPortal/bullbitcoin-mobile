// ignore_for_file: avoid_print
//
// novlang_bridge.dart — dev-only generator for the novlang overrides.
//
// Run by `make translations` after every `gen-l10n`. It reads
// `packages/novlang/manifest.yaml` and, for each catalogue it declares, the
// code gen-l10n already generated for that catalogue (located through the
// `l10n.yaml` of the catalogue's package), and writes (git-ignored)
// `novlang_<catalogue>_localizations.dart` to the catalogue's configured
// output directory (default: `lib/generated/novlang`):
//
//   * one `Novlang<Class><Lang>` class per generated `<Class><Lang>` class,
//     extending it, so locale/script/region resolution stays entirely
//     gen-l10n's;
//   * a mixin that overrides ONLY the manifest keys of that catalogue (getters
//     and methods, with the signatures gen-l10n generated, so ICU stays
//     gen-l10n's job) and reads the `NovlangLocalizations` override when the
//     policy of the entry's store applies, otherwise `super` (the real word);
//   * `Novlang<Class>Delegate`, wrapping the catalogue's delegate (the stock
//     `<Class>.delegate` by default, or the one the shell already uses, such
//     as a fallback delegate), composed in its place.
//
// The root catalogue (`app`) also gets `novlangLocalizationsDelegates`.
//
// A manifest key that no longer exists in its catalogue fails this tool; an
// override key missing from the novlang catalogue fails compilation. Nothing
// here patches generated code or parses ICU.
//
// Usage (from the repository root): dart tools/novlang_bridge.dart
// (`dart run` would trigger the native build hooks of the app for nothing.)

import 'dart:io';

import 'package:yaml/yaml.dart';

const _manifestPath = 'packages/novlang/manifest.yaml';
const _outputDir = 'lib/generated/novlang';

void main(List<String> args) {
  final manifest = _readManifest();
  for (final catalogue in manifest.catalogues) {
    _generate(catalogue, [
      for (final e in manifest.entries)
        if (e.catalogue == catalogue.id) e,
    ]);
  }
}

void _generate(_Catalogue c, List<_Entry> entries) {
  final signatures = _readSignatures(c);
  final locales = _readLocaleClasses(c);

  final arbCount = Directory(c.arbDir)
      .listSync()
      .whereType<File>()
      .where((f) => RegExp('/${c.arbPrefix}_\\w+\\.arb\$').hasMatch(f.path))
      .length;
  if (locales.length != arbCount) {
    stderr.writeln(
      'Found ${locales.length} generated locale classes for $arbCount '
      'catalogues in ${c.arbDir}: a language would silently keep the real '
      'words. Run gen-l10n first, or extend this tool if gen-l10n changed its '
      'output.',
    );
    exit(1);
  }

  final missing = [
    for (final e in entries)
      if (!signatures.containsKey(e.key)) e.key,
  ];
  if (missing.isNotEmpty) {
    stderr.writeln(
      'novlang manifest keys missing from the ${c.id} catalogue: '
      '${missing.join(', ')}',
    );
    exit(1);
  }

  final cls = c.className;
  final mixin = 'Novlang${_pascal(c.id)}Overrides';
  final delegate = 'Novlang${cls}Delegate';
  final stores = {for (final e in entries) e.store}.toList()..sort();
  final out = StringBuffer()
    ..writeln('// GENERATED by tools/novlang_bridge.dart. Do not edit.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln();
  if (c.isRoot) {
    out.writeln(
      "import 'package:bb_mobile/localizations.dart' "
      'show appLocalizationsDelegates;',
    );
  }
  out.writeln("import '${c.importPrefix}/${c.outputFile}';");
  for (final file in locales.map((l) => l.file).toSet().toList()..sort()) {
    out.writeln("import '${c.importPrefix}/$file';");
  }
  out
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln("import 'package:novlang/novlang.dart';")
    ..writeln()
    ..writeln(
      '/// Overrides only the keys of the novlang manifest; every other\n'
      '/// message comes from the catalogue untouched.',
    )
    ..writeln('mixin $mixin on $cls {')
    ..writeln('  NovlangPolicy get novlangPolicy;')
    ..writeln('  NovlangLocalizations get novlang;');
  for (final e in entries) {
    final s = signatures[e.key]!;
    final value = 'novlang.${c.id}__${e.key}_${e.store}';
    final applies = 'novlangPolicy == NovlangPolicy.${e.store}';
    out.writeln();
    out.writeln('  @override');
    if (s.params == null) {
      out
        ..writeln('  String get ${e.key} =>')
        ..writeln('      $applies ? $value : super.${e.key};');
    } else {
      final names = _paramNames(s.params!);
      final call = names.isEmpty ? '' : names.join(', ');
      out
        ..writeln('  String ${e.key}(${s.params}) =>')
        ..writeln('      $applies ? $value($call) : super.${e.key}($call);');
    }
  }
  out.writeln('}');

  for (final l in locales) {
    out
      ..writeln()
      ..writeln('class ${l.novlangName} extends ${l.name} with $mixin {')
      ..writeln('  ${l.novlangName}(this.novlangPolicy, this.novlang);')
      ..writeln()
      ..writeln('  @override')
      ..writeln('  final NovlangPolicy novlangPolicy;')
      ..writeln()
      ..writeln('  @override')
      ..writeln('  final NovlangLocalizations novlang;')
      ..writeln('}');
  }

  out
    ..writeln()
    ..writeln('/// Policies with at least one override in the manifest.')
    ..writeln('const _constrainedPolicies = <NovlangPolicy>{')
    ..writeln([for (final s in stores) '  NovlangPolicy.$s,'].join('\n'))
    ..writeln('};')
    ..writeln()
    ..writeln(
      '/// Serves [$cls] with the store vocabulary of [policy].\n'
      '///\n'
      '/// Place it BEFORE any other `$cls` delegate: Flutter uses the\n'
      '/// first delegate of a type. [base] resolves the locale; this only\n'
      '/// wraps its result.',
    )
    ..writeln('class $delegate extends LocalizationsDelegate<$cls> {')
    ..writeln('  const $delegate(this.policy, [this.base = $cls.delegate]);')
    ..writeln()
    ..writeln('  final NovlangPolicy policy;')
    ..writeln()
    ..writeln('  /// The catalogue delegate whose result is wrapped.')
    ..writeln('  final LocalizationsDelegate<$cls> base;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  bool isSupported(Locale locale) => base.isSupported(locale);')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  Future<$cls> load(Locale locale) async {')
    ..writeln('    final loaded = await base.load(locale);')
    ..writeln('    if (!_constrainedPolicies.contains(policy)) return loaded;')
    ..writeln('    final novlang = lookupNovlangLocalizations(locale);')
    ..writeln('    return switch (loaded.localeName) {');
  for (final l in locales) {
    out.writeln(
      "      '${l.localeName}' => ${l.novlangName}(policy, novlang),",
    );
  }
  out
    ..writeln(
      "      _ => throw StateError('No novlang class for "
      "\${loaded.localeName}'),",
    )
    ..writeln('    };')
    ..writeln('  }')
    ..writeln()
    ..writeln('  @override')
    ..writeln(
      '  bool shouldReload($delegate old) =>\n'
      '      old.policy != policy || old.base != base;',
    )
    ..writeln('}');

  if (c.isRoot) {
    out
      ..writeln()
      ..writeln(
        '/// The delegates of every MaterialApp showing catalogue text: the\n'
        '/// novlang delegate FIRST, then the stock ones. A MaterialApp that\n'
        '/// lists only `AppLocalizations.localizationsDelegates` would bypass\n'
        '/// novlang.',
      )
      ..writeln(
        'List<LocalizationsDelegate<dynamic>> novlangLocalizationsDelegates(\n'
        '  NovlangPolicy policy,\n'
        ') => [\n'
        '  $delegate(policy),\n'
        '  ...appLocalizationsDelegates,\n'
        '];',
      );
  }

  final path = '${c.novlangDir}/novlang_${c.id}_localizations.dart';
  File(path)
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  print(
    'novlang: ${c.id}: ${entries.length} overrides, ${locales.length} locale '
    'classes -> $path',
  );
}

class _Manifest {
  const _Manifest(this.catalogues, this.entries);
  final List<_Catalogue> catalogues;
  final List<_Entry> entries;
}

/// A gen-l10n catalogue, located through the `l10n.yaml` of its package.
class _Catalogue {
  factory _Catalogue(String id, YamlMap catalogue) {
    final dir = catalogue['path'] as String;
    final l10n = loadYaml(File('$dir/l10n.yaml').readAsStringSync()) as YamlMap;
    final pubspec =
        loadYaml(File('$dir/pubspec.yaml').readAsStringSync()) as YamlMap;
    final outputDir = l10n['output-dir'] as String;
    if (!outputDir.startsWith('lib/')) {
      stderr.writeln('$dir/l10n.yaml: output-dir must be under lib/.');
      exit(1);
    }
    return _Catalogue._(
      id: id,
      arbDir: '$dir/${l10n['arb-dir']}',
      arbPrefix: (l10n['template-arb-file'] as String).replaceFirst(
        RegExp(r'_[^_]+\.arb$'),
        '',
      ),
      l10nDir: '$dir/$outputDir',
      outputFile: l10n['output-localization-file'] as String,
      className: (l10n['output-class'] as String?) ?? 'AppLocalizations',
      novlangDir: (catalogue['output-dir'] as String?) ?? _outputDir,
      importPrefix:
          'package:${pubspec['name']}/${outputDir.substring('lib/'.length)}',
    );
  }

  const _Catalogue._({
    required this.id,
    required this.arbDir,
    required this.arbPrefix,
    required this.l10nDir,
    required this.outputFile,
    required this.className,
    required this.importPrefix,
    required this.novlangDir,
  });

  final String id;
  final String arbDir;
  final String arbPrefix;
  final String l10nDir;
  final String outputFile;
  final String className;
  final String importPrefix;
  final String novlangDir;

  bool get isRoot => id == 'app';
}

class _Entry {
  const _Entry(this.catalogue, this.key, this.store);
  final String catalogue;
  final String key;
  final String store;
}

class _Signature {
  const _Signature(this.params);

  /// `null` for a getter, the raw parameter list for a method.
  final String? params;
}

class _LocaleClass {
  const _LocaleClass(this.name, this.file, this.localeName);
  final String name;
  final String file;
  final String localeName;
  String get novlangName => 'Novlang$name';
}

String _pascal(String id) => [
  for (final w in id.split('_'))
    if (w.isNotEmpty) w[0].toUpperCase() + w.substring(1),
].join();

_Manifest _readManifest() {
  final yaml = loadYaml(File(_manifestPath).readAsStringSync()) as YamlMap;
  final stores = (yaml['stores'] as YamlMap).keys.cast<String>().toSet();
  final catalogues = [
    for (final MapEntry(:key, :value)
        in (yaml['catalogues'] as YamlMap).entries)
      _Catalogue(key as String, value as YamlMap),
  ];
  final ids = {for (final c in catalogues) c.id};
  if (!ids.contains('app')) {
    stderr.writeln('The novlang manifest must declare the root catalogue app.');
    exit(1);
  }
  final entries = <_Entry>[];
  final seen = <String>{};
  for (final raw in yaml['entries'] as YamlList) {
    final e = raw as YamlMap;
    final catalogue = e['catalogue'] as String;
    final key = e['key'] as String;
    final store = e['store'] as String;
    if (!ids.contains(catalogue)) {
      stderr.writeln('Unknown novlang catalogue "$catalogue" for $key.');
      exit(1);
    }
    if (!stores.contains(store)) {
      stderr.writeln('Unknown store "$store" for $key.');
      exit(1);
    }
    if (!seen.add('$catalogue/$store/$key')) {
      stderr.writeln('Duplicate manifest entry $catalogue/$store/$key.');
      exit(1);
    }
    entries.add(_Entry(catalogue, key, store));
  }
  return _Manifest(catalogues, entries);
}

/// Getter and method signatures of the abstract catalogue class.
Map<String, _Signature> _readSignatures(_Catalogue c) {
  final source = File('${c.l10nDir}/${c.outputFile}').readAsStringSync();
  final re = RegExp(
    r'^  String (?:get (\w+)|(\w+)\(([^)]*)\));',
    multiLine: true,
  );
  final result = <String, _Signature>{};
  for (final m in re.allMatches(source)) {
    final getter = m.group(1);
    if (getter != null) {
      result[getter] = const _Signature(null);
    } else {
      result[m.group(2)!] = _Signature(_normalizeParams(m.group(3)!));
    }
  }
  return result;
}

String _normalizeParams(String raw) =>
    raw.replaceAll(RegExp(r'\s+'), ' ').trim().replaceAll(RegExp(r',$'), '');

List<String> _paramNames(String params) => [
  for (final p in params.split(','))
    if (p.trim().isNotEmpty) p.trim().split(' ').last,
];

/// Every generated `<Class><Lang>` class of [c] with its locale name.
List<_LocaleClass> _readLocaleClasses(_Catalogue c) {
  final classes = <_LocaleClass>[];
  final stem = c.outputFile.replaceFirst(RegExp(r'\.dart$'), '');
  final files =
      Directory(c.l10nDir)
          .listSync()
          .whereType<File>()
          .where((f) => RegExp('/${stem}_\\w+\\.dart\$').hasMatch(f.path))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final cls = c.className;
  final langRe = RegExp(
    'class ($cls\\w+) extends $cls \\{\\s+'
    "\\1\\(\\[String locale = '(\\w+)'\\]\\)",
  );
  final regionRe = RegExp(
    'class ($cls\\w+) extends $cls\\w+ \\{\\s+'
    "\\1\\(\\) : super\\('(\\w+)'\\);",
  );
  for (final f in files) {
    final source = f.readAsStringSync();
    final file = f.uri.pathSegments.last;
    for (final m in [
      ...langRe.allMatches(source),
      ...regionRe.allMatches(source),
    ]) {
      classes.add(_LocaleClass(m.group(1)!, file, m.group(2)!));
    }
  }
  if (classes.isEmpty) {
    stderr.writeln('No generated locale class found in ${c.l10nDir}.');
    exit(1);
  }
  return classes;
}
