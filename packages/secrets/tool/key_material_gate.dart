/// A resolved-symbol boundary, not a whole-program secret-flow analysis.
///
/// Imports, re-exports, aliases and tear-offs resolve to the declaration being
/// used. The test keystore is also forbidden in production consumers.
/// Validation, word lists, mnemonic formatting and public-key derivation
/// remain available to the app. New cryptographic dependencies or APIs require
/// updating this policy; arbitrary cryptography and dynamic dispatch are not
/// proven safe by this gate. Analysis errors fail closed.
Future<void> main(List<String> arguments) async {
  final root = Directory(arguments.isEmpty ? '.' : arguments.single).absolute;
  final report = await checkKeyMaterial(root.path);
  for (final violation in report.violations) {
    stderr.writeln(violation);
  }
  stdout.writeln(
    'Key-material boundary: ${report.fileCount} files, '
    '${report.violations.length} violations',
  );
  if (report.violations.isNotEmpty) exitCode = 1;
}

class KeyMaterialReport {
  final int fileCount;
  final List<String> violations;

  const KeyMaterialReport(this.fileCount, this.violations);
}

Future<KeyMaterialReport> checkKeyMaterial(String rootPath) async {
  final root = Directory(rootPath).resolveSymbolicLinksSync();
  final collection = AnalysisContextCollection(
    includedPaths: [root],
    sdkPath: dartSdkPath(root),
  );
  final files = productionDartFiles(root);
  final violations = <String>[];
  for (final path in bindingsDartFiles(root)) {
    final result = await collection
        .contextFor(path)
        .currentSession
        .getResolvedUnit(path);
    final relative = path.substring(root.length + 1);
    if (result is! ResolvedUnitResult) {
      violations.add('$relative: unresolved unit (bindings boundary)');
      continue;
    }
    for (final diagnostic in result.diagnostics) {
      if (diagnostic.diagnosticCode.severity.name == 'ERROR') {
        violations.add('$relative: ${diagnostic.diagnosticCode.lowerCaseName}');
      }
    }
    violations.addAll(checkSecretsReach(result.unit, relative, root: root));
  }
  for (final path in files) {
    final relative = path.substring(root.length + 1);
    final result = await collection
        .contextFor(path)
        .currentSession
        .getResolvedUnit(path);
    if (result is! ResolvedUnitResult) {
      violations.add('$relative: unresolved unit');
      continue;
    }
    for (final diagnostic in result.diagnostics) {
      if (diagnostic.diagnosticCode.severity.name == 'ERROR') {
        violations.add('$relative: ${diagnostic.diagnosticCode.lowerCaseName}');
      }
    }
    violations.addAll(checkUnit(result.unit, relative));
  }
  await collection.dispose();
  return KeyMaterialReport(files.length, violations.toSet().toList()..sort());
}

List<String> productionDartFiles(String root) {
  final roots = <Directory>[Directory('$root/lib')];
  for (final group in ['packages', 'features']) {
    final parent = Directory('$root/$group');
    if (!parent.existsSync()) continue;
    for (final member in parent.listSync(followLinks: false)) {
      if (member is Directory && member.path != '$root/packages/secrets') {
        roots.add(Directory('${member.path}/lib'));
      }
    }
  }
  return [
    // Audit signing too: it must use the language-aware seed, never BDK words.
    if (File('$root/$_bitcoinSignerPath').existsSync())
      '$root/$_bitcoinSignerPath',
    for (final directory in roots)
      if (directory.existsSync())
        for (final file in directory.listSync(
          recursive: true,
          followLinks: false,
        ))
          if (file is File &&
              file.path.endsWith('.dart') &&
              // The generated bridge declares the binding types (SwapMasterKey,
              // Wallet) and calls them; hand-written files are checked, there
              // too.
              !_isGeneratedBridge(root, file) &&
              !RegExp(r'\.(g|freezed|gr|config|mocks|steps|drift)\.dart$')
                  .hasMatch(file.path) &&
              !file.path
                  .split(Platform.pathSeparator)
                  .any(
                    (part) => ['generated', 'vendor', 'build'].contains(part),
                  ))
            file.path,
  ]..sort();
}

/// A flutter_rust_bridge output file of rust_bindings, recognized by the
/// header the generator writes, not by its directory alone.
bool _isGeneratedBridge(String root, File file) =>
    file.path.startsWith('$root/packages/rust_bindings/lib/src/rust/') &&
    file.readAsLinesSync().firstOrNull ==
        '// This file is automatically generated, so please do not edit it.';

/// Every Dart file of the bindings packages, generated output included: the
/// seal-ignore exemption of their generated bridge holds only if none of them
/// can reach package:secrets, whatever the import spelling or header.
List<String> bindingsDartFiles(String root) => [
  for (final package in ['rust_bindings', 'onion'])
    if (Directory('$root/packages/$package').existsSync())
      for (final file in Directory(
        '$root/packages/$package',
      ).listSync(recursive: true, followLinks: false))
        if (file is File &&
            file.path.endsWith('.dart') &&
            !file.path
                .split(Platform.pathSeparator)
                .any(
                  (part) => {'build', '.dart_tool', 'target'}.contains(part),
                ))
          file.path,
]..sort();

/// Rejects any directive or element of [unit] that resolves into
/// package:secrets, judged on the resolved library, not on the URI text.
List<String> checkSecretsReach(
  CompilationUnit unit,
  String relativePath, {
  required String root,
}) {
  final package = relativePath.split('/').take(2).join('/');
  final visitor = _SecretsReachVisitor(relativePath, '$root/$package/');
  unit.accept(visitor);
  return visitor.violations.toList()..sort();
}

bool _isSecretsLibrary(LibraryElement? library) {
  final uri = library?.uri;
  if (uri == null) return false;
  return (uri.isScheme('package') && uri.pathSegments.first == 'secrets') ||
      (uri.isScheme('file') && uri.path.contains('/packages/secrets/lib/'));
}

class _SecretsReachVisitor extends RecursiveAstVisitor<void> {
  final String path;
  final String packageDirectory;
  final Set<String> violations = {};

  _SecretsReachVisitor(this.path, this.packageDirectory);

  void _report(LibraryElement? library) {
    if (_isSecretsLibrary(library)) {
      violations.add('$path: reaches ${library?.uri} (bindings boundary)');
    }
  }

  /// A resolved directive URI, whichever conditional alternative it is.
  void _reportUri(DirectiveUri? uri) {
    if (uri is DirectiveUriWithLibrary) _report(uri.library);
    if (uri is DirectiveUriWithSource &&
        uri.source.fullName.contains('/packages/secrets/')) {
      violations.add(
        '$path: reaches ${uri.source.fullName} (bindings boundary)',
      );
    }
  }

  /// Every URI written in [node], the default included when an alternative
  /// is selected, resolved against the file that contains it.
  void _reportWritten(NamespaceDirective node) {
    final file = node
        .thisOrAncestorOfType<CompilationUnit>()
        ?.declaredFragment
        ?.source
        .fullName;
    for (final text in [
      node.uri.stringValue,
      for (final configuration in node.configurations)
        configuration.uri.stringValue,
    ]) {
      final uri = text == null ? null : Uri.tryParse(text);
      if (uri == null) continue;
      final resolved = file == null ? uri : Uri.file(file).resolveUri(uri);
      if ((resolved.isScheme('package') &&
              resolved.pathSegments.firstOrNull == 'secrets') ||
          (resolved.isScheme('file') &&
              resolved.path.contains('/packages/secrets/'))) {
        violations.add('$path: reaches $text (bindings boundary)');
      }
    }
  }

  @override
  void visitImportDirective(ImportDirective node) {
    _report(node.libraryImport?.importedLibrary);
    for (final configuration in node.configurations) {
      _reportUri(configuration.resolvedUri);
    }
    _reportWritten(node);
    super.visitImportDirective(node);
  }

  @override
  void visitExportDirective(ExportDirective node) {
    _report(node.libraryExport?.exportedLibrary);
    for (final configuration in node.configurations) {
      _reportUri(configuration.resolvedUri);
    }
    _reportWritten(node);
    super.visitExportDirective(node);
  }

  /// A part outside the package would be compiled in without being scanned.
  @override
  void visitPartDirective(PartDirective node) {
    final uri = node.partInclude?.uri;
    if (uri is DirectiveUriWithSource &&
        !uri.source.fullName.startsWith(packageDirectory)) {
      violations.add('$path: part outside its package (bindings boundary)');
    }
    super.visitPartDirective(node);
  }

  @override
  void visitSimpleIdentifier(SimpleIdentifier node) {
    _report(node.element?.library);
    super.visitSimpleIdentifier(node);
  }

  @override
  void visitNamedType(NamedType node) {
    _report(node.element?.library);
    super.visitNamedType(node);
  }
}

List<String> checkUnit(CompilationUnit unit, String relativePath) {
  final visitor = _KeyMaterialVisitor(relativePath);
  unit.accept(visitor);
  return visitor.violations.toList()..sort();
}

class _KeyMaterialVisitor extends RecursiveAstVisitor<void> {
  final String path;
  final Set<String> violations = {};

  _KeyMaterialVisitor(this.path);

  void check(Element? element, AstNode node) {
    if (element == null) {
      if (node is SimpleIdentifier &&
          _unresolvedSensitiveMembers.contains(node.name) &&
          (node.parent is PropertyAccess ||
              node.parent is PrefixedIdentifier ||
              node.parent is MethodInvocation ||
              node.parent is DotShorthandInvocation)) {
        violations.add('$path: unresolved sensitive member ${node.name}');
      }
      return;
    }
    final symbol = materialSymbol(element);
    if (symbol == null || _isException(path, node, symbol)) return;
    violations.add('$path: $symbol');
  }

  void checkTestingLibrary(String? uri) {
    if (uri != null && _isTestingLibrary(uri)) {
      violations.add('$path: $uri#test-only library');
    }
  }

  @override
  void visitImportDirective(ImportDirective node) {
    checkTestingLibrary(node.libraryImport?.importedLibrary?.uri.toString());
    checkTestingLibrary(node.uri.stringValue);
    for (final configuration in node.configurations) {
      checkTestingLibrary(configuration.uri.stringValue);
    }
    super.visitImportDirective(node);
  }

  @override
  void visitExportDirective(ExportDirective node) {
    checkTestingLibrary(node.libraryExport?.exportedLibrary?.uri.toString());
    checkTestingLibrary(node.uri.stringValue);
    for (final configuration in node.configurations) {
      checkTestingLibrary(configuration.uri.stringValue);
    }
    super.visitExportDirective(node);
  }

  // The bridge's default handler is the only one that sees call arguments: a
  // host handler or API would receive the words handed to lwk, boltz and bwk.
  @override
  void visitMethodInvocation(MethodInvocation node) {
    final element = node.methodName.element;
    if (element is ExecutableElement &&
        element.library.uri.toString() == _bridgeLibrary &&
        element.enclosingElement?.name == 'BullSdk' &&
        element.name == 'init' &&
        node.argumentList.arguments.isNotEmpty) {
      violations.add('$path: $_bridgeLibrary#BullSdk.init with arguments');
    }
    super.visitMethodInvocation(node);
  }

  @override
  void visitCommentReference(CommentReference node) {}

  @override
  void visitSimpleIdentifier(SimpleIdentifier node) {
    if (!node.inDeclarationContext()) check(node.element, node);
    super.visitSimpleIdentifier(node);
  }

  @override
  void visitConstructorName(ConstructorName node) {
    check(node.element, node);
    super.visitConstructorName(node);
  }

  @override
  void visitDotShorthandConstructorInvocation(
    DotShorthandConstructorInvocation node,
  ) {
    check(node.element, node);
    super.visitDotShorthandConstructorInvocation(node);
  }
}

// Dynamic or otherwise unresolved access to these sensitive entry points must
// be replaced by a statically resolved call. Generic names such as `sign` are
// deliberately absent: this is not a blanket ban on dynamic app data.
const _unresolvedSensitiveMembers = {
  'seed',
  'fromSeed',
  'fromPrivateKey',
  'deriveHardened',
  'secretBytes',
  'newConfidential',
  'newConfidentialFromSeed',
  'restoreBackup',
  'signedPsetWithExtraDetails',
  'signedPsetWithExtraDetailsWithSeed',
  'signTxWithSeed',
  'createFromSeed',
  'createFromSeedWithScanRuntime',
  'deriveSpAddressFromSeed',
  // Secret's internal members that hand back or use key material: a dynamic
  // call reaches them without the analyzer seal ever seeing it.
  'revealMnemonic',
  'bip85Hex',
  'bip85Mnemonic',
  'swapKey',
  'signPsbt',
  'signPset',
  'silentPaymentsAccount',
  'backupRecoverbull',
  'restoreRecoverbull',
};

const _bridgeLibrary = 'package:rust_bindings/src/rust/frb_generated.dart';

// A relative URI in an inactive conditional alternative is never resolved, so
// it is matched on its path.
bool _isTestingLibrary(String uri) =>
    uri == 'package:secrets/testing.dart' ||
    uri == 'package:rust_bindings/testing.dart' ||
    (!uri.contains(':') &&
        RegExp(r'(^|/)rust_bindings/lib/testing\.dart$')
            .hasMatch(Uri.parse(uri).normalizePath().path)) ||
    uri.startsWith('package:secrets/src/testing/') ||
    (!uri.contains(':') &&
        RegExp(r'(^|/)secrets/lib/(testing\.dart$|src/testing/)')
            .hasMatch(Uri.parse(uri).normalizePath().path));

String? materialSymbol(Element element) {
  final uri = element.library?.uri.toString();
  if (uri != null && _isTestingLibrary(uri)) {
    return '$uri#${element.name}';
  }
  if (element is! ExecutableElement || uri == null) return null;
  final owner = element.enclosingElement?.name;
  final member = element.name;
  final symbol = '$owner.$member';
  final forbidden = switch (uri) {
    _ when uri.startsWith('package:bip39_mnemonic/') =>
      symbol == 'Mnemonic.seed',
    _ when uri.startsWith('package:bip32_keys/') =>
      owner == 'Bip32Keys' &&
          {
            'new',
            'fromSeed',
            'fromBase58',
            'fromPrivateKey',
            'private',
            'deriveHardened',
            'sign',
            'toWIF',
          }.contains(member),
    _ when uri.startsWith('package:bip85_entropy/') =>
      owner == 'Bip85Entropy' && (member?.startsWith('derive') ?? false),
    _ when uri.startsWith('package:bdk_dart/') =>
      {'DescriptorSecretKey', 'DescriptorSecretKeyInterface'}.contains(owner) ||
          (owner == 'Mnemonic' && element is ConstructorElement) ||
          (owner == 'Descriptor' &&
              {
                'newBip44',
                'newBip49',
                'newBip84',
                'newBip86',
              }.contains(member)),
    'package:rust_bindings/src/lwk_consolidate.dart' => member == 'batchSign',
    _ when uri.startsWith('package:rust_bindings/src/rust/third_party/lwk/') =>
      {
        'Descriptor.newConfidential',
        'Descriptor.newConfidentialFromSeed',
        'Wallet.signTx',
        'Wallet.signTxWithSeed',
        'Wallet.signedPsetWithExtraDetails',
        'Wallet.signedPsetWithExtraDetailsWithSeed',
      }.contains(symbol),
    _
        when uri.startsWith(
          'package:rust_bindings/src/rust/third_party/boltz/',
        ) =>
      owner == 'SwapMasterKey' &&
          {
            'new',
            'create',
            'createFromSeed',
            'xprv',
            'mnemonic',
          }.contains(member),
    _
        when uri.startsWith(
          'package:rust_bindings/src/rust/third_party/dart_bwk/',
        ) =>
      (owner == 'SpAccount' &&
              ((member?.startsWith('createFromMnemonic') ?? false) ||
                  (member?.startsWith('createFromSeed') ?? false))) ||
          member == 'deriveSpAddressFromSeed',
    _bridgeLibrary => symbol == 'BullSdk.initMock',
    _ when uri.startsWith('package:recoverbull/') =>
      symbol == 'RecoverBull.restoreBackup' ||
          symbol == 'EncryptionService.decrypt',
    _ => false,
  };
  return forbidden ? '$uri#$symbol' : null;
}

const _bitcoinSignerPath =
    'packages/secrets/lib/src/crypto/signers/bitcoin_signer.dart';

bool _isException(String path, AstNode node, String symbol) {
  String? function;
  String? owner;
  for (AstNode? current = node; current != null; current = current.parent) {
    if (current is FunctionDeclaration) function = current.name.lexeme;
    if (current is MethodDeclaration) function = current.name.lexeme;
    if (current is ConstructorDeclaration) {
      function = current.name?.lexeme ?? 'new';
    }
    if (current is ClassDeclaration) owner = current.namePart.typeName.lexeme;
  }
  final member = symbol.split('#').last;
  if (path == _bitcoinSignerPath &&
      owner == 'BitcoinSigner' &&
      function == '_wallet' &&
      {
        'DescriptorSecretKey.fromString',
        'DescriptorSecretKey.dispose',
      }.contains(member)) {
    return true;
  }
  // This adapter replaces version bytes with the public xpub version before
  // decoding. Elsewhere this mixed decoder could import private extended keys.
  if (path == 'packages/satoshifier/lib/bip32_derivation.dart' &&
      owner == 'Bip32Derivation' &&
      function == 'getBip32Xpub' &&
      member == 'Bip32Keys.fromBase58') {
    return true;
  }
  // The consolidation helper signs with the words it is given; its callers
  // are checked through `batchSign` itself.
  if (path == 'packages/rust_bindings/lib/src/lwk_consolidate.dart' &&
      function == 'batchSign' &&
      member == 'Wallet.signTx') {
    return true;
  }
  // satoshifier decodes extended public keys with this mixed decoder: by
  // prefix in ExtendedPubkey.parse, and by refusing a non-neutered key in
  // Descriptor._requirePublicKey. Listed precisely so that any other use is
  // still flagged.
  if (member == 'Bip32Keys.fromBase58' &&
      {
            'packages/satoshifier/lib/extended_pubkey.dart': {
              ('ExtendedPubkey', 'parse'),
            },
            'packages/satoshifier/lib/descriptor.dart': {
              ('Descriptor', '_requirePublicKey'),
            },
            'packages/satoshifier/lib/utils/bip32_utils.dart': {
              ('Bip32Utils', 'fingerprint'),
              ('Bip32Utils', 'convertToXpub'),
              ('Bip32Utils', 'convertToYpub'),
              ('Bip32Utils', 'convertToZpub'),
            },
          }[path]?.contains((owner, function)) ==
          true) {
    return true;
  }
  // The exported swap master key is a documented, independent child secret.
  if (path == 'packages/swaps/lib/src/data/models/swap_master_key_model.dart' &&
      owner == 'SwapMasterKeyModel') {
    return (function == 'fromBoltz' &&
            {
              'SwapMasterKey.xprv',
              'SwapMasterKey.mnemonic',
            }.contains(member)) ||
        (function == 'toBoltz' && member == 'SwapMasterKey.new');
  }
  return false;
}

String dartSdkPath(String start) {
  var directory = Directory(start);
  while (true) {
    final config = File('${directory.path}/.dart_tool/package_config.json');
    if (config.existsSync()) {
      final packages =
          (jsonDecode(config.readAsStringSync()) as Map)['packages'] as List;
      final flutter = packages.cast<Map>().firstWhere(
        (p) => p['name'] == 'flutter',
      );
      final root = config.uri
          .resolve(flutter['rootUri'] as String)
          .toFilePath();
      return '${Directory(root).parent.parent.path}/bin/cache/dart-sdk';
    }
    if (directory.parent.path == directory.path) {
      throw StateError('No package_config.json');
    }
    directory = directory.parent;
  }
}
